-- V1__saas.sql: esquema inicial del backend SaaS (Fase 8, según
-- docs/saas/ARCHITECTURE.md). Vive en el SCHEMA dedicado saas para no
-- chocar con las tablas de v2 (users, activations) en la misma BD de
-- Supabase. Sin tarjetas: los datos de pago NUNCA tocan la base de datos.
-- Idempotente: puede re-ejecutarse sin daño.
--
-- Portabilidad H2/Postgres: BYTEA es nativo de Postgres y H2 lo acepta en
-- modo compatibilidad (URL con MODE=PostgreSQL). BYTEA no lleva longitud.
-- ATENCIÓN: SchemaInitializer parte el script por punto y coma, así que
-- este archivo NO debe contener punto y coma dentro de los comentarios.

CREATE SCHEMA IF NOT EXISTS saas;

CREATE TABLE IF NOT EXISTS saas.plans (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         VARCHAR(32)  NOT NULL UNIQUE,
    price_cents  INT          NOT NULL,
    currency     VARCHAR(8)   NOT NULL DEFAULT 'MXN',
    period       VARCHAR(16)  NOT NULL,
    active       BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS saas.users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_hash     VARCHAR(64)  NOT NULL UNIQUE,
    email_enc      BYTEA,
    password_hash  VARCHAR(72)  NOT NULL,
    first_name_enc BYTEA,
    last_name_enc  BYTEA,
    salt           BYTEA,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS saas.subscriptions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL,
    plan_id      BIGINT       NOT NULL,
    status       VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    started_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    next_billing TIMESTAMP WITH TIME ZONE,
    canceled_at  TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_saas_sub_user FOREIGN KEY (user_id) REFERENCES saas.users (id),
    CONSTRAINT fk_saas_sub_plan FOREIGN KEY (plan_id) REFERENCES saas.plans (id)
);

CREATE TABLE IF NOT EXISTS saas.payments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      NOT NULL,
    subscription_id BIGINT,
    gateway         VARCHAR(32) NOT NULL,
    external_id     VARCHAR(128),
    amount_cents    INT         NOT NULL,
    currency        VARCHAR(8)  NOT NULL DEFAULT 'MXN',
    status          VARCHAR(16) NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_saas_pay_user FOREIGN KEY (user_id) REFERENCES saas.users (id)
);

CREATE TABLE IF NOT EXISTS saas.license_tokens (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      NOT NULL,
    subscription_id BIGINT      NOT NULL,
    token_hash      VARCHAR(64) NOT NULL UNIQUE,
    issued_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    last_heartbeat  TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_saas_lt_user FOREIGN KEY (user_id) REFERENCES saas.users (id),
    CONSTRAINT fk_saas_lt_sub  FOREIGN KEY (subscription_id) REFERENCES saas.subscriptions (id)
);

CREATE INDEX IF NOT EXISTS ix_saas_sub_user ON saas.subscriptions (user_id);
CREATE INDEX IF NOT EXISTS ix_saas_lt_user  ON saas.license_tokens (user_id);
