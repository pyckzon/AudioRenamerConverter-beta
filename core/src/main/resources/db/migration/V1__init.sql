-- V1__init.sql: esquema inicial de MP3Converter (Fase 4, requisito 2.5.2).
-- Sin tarjetas: los datos de pago NUNCA tocan la base de datos.
-- Idempotente: puede re-ejecutarse sin daño (SchemaInitializer lo garantiza).
--
-- Portabilidad H2/Postgres (integración Supabase real): los binarios usan
-- BYTEA, tipo nativo de Postgres que H2 acepta en modo de compatibilidad
-- (URL de H2 con MODE=PostgreSQL lo aliasa a VARBINARY). BYTEA no lleva
-- longitud en ninguno de los dos motores.
-- ATENCIÓN: SchemaInitializer parte este script por punto y coma, así que
-- este archivo NO debe contener punto y coma dentro de los comentarios.

CREATE TABLE IF NOT EXISTS users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_hash      VARCHAR(64)  NOT NULL UNIQUE,
    email_enc       BYTEA,
    first_name_enc  BYTEA,
    last_name_enc   BYTEA,
    phone_enc       BYTEA,
    tier            VARCHAR(16)  NOT NULL DEFAULT 'FREE',
    salt            BYTEA NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS activations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL,
    code_hash       VARCHAR(64) NOT NULL UNIQUE,
    code_enc        BYTEA NOT NULL,
    salt            BYTEA NOT NULL,
    issued_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status          VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    deactivated_at  TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_activations_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX IF NOT EXISTS ix_activations_user ON activations (user_id);
