-- V1__init.sql: esquema inicial de MP3Converter (Fase 4, requisito 2.5.2).
-- Sin tarjetas: los datos de pago NUNCA tocan la base de datos.
-- Idempotente: puede re-ejecutarse sin daño (SchemaInitializer lo garantiza).

CREATE TABLE IF NOT EXISTS users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_hash      VARCHAR(64)  NOT NULL UNIQUE,
    email_enc       VARBINARY(4096),
    first_name_enc  VARBINARY(4096),
    last_name_enc   VARBINARY(4096),
    phone_enc       VARBINARY(4096),
    tier            VARCHAR(16)  NOT NULL DEFAULT 'FREE',
    salt            VARBINARY(64) NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS activations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL,
    code_hash       VARCHAR(64) NOT NULL UNIQUE,
    code_enc        VARBINARY(4096) NOT NULL,
    salt            VARBINARY(64) NOT NULL,
    issued_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status          VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    deactivated_at  TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_activations_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX IF NOT EXISTS ix_activations_user ON activations (user_id);
